import {readFile,writeFile,copyFile} from 'node:fs/promises';
import sharp from 'sharp';
import {withStartupAssets} from './startup-assets.mjs';
import {pwaBackgrounds, withPwaHead} from './pwa-head.mjs';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=new URL('../scratch/asar/webview/',import.meta.url);
await copyFile(new URL('mobile.css',import.meta.url),new URL('assets/mobile.css',root));
await copyFile(new URL('mobile-pwa.js',import.meta.url),new URL('assets/mobile-pwa.js',root));
let html=await readFile(new URL('index.html',root),'utf8');
html=html.replace(/<script data-startup-status>[\s\S]*?<\/script>/,'');
html=html.replace('<head>', '<head><script data-startup-status>'+await readFile(new URL('startup-status.js',import.meta.url),'utf8')+'</script>');
html=html.replace(/<link\b[^>]*rel="manifest"[^>]*>/,'<link rel="manifest" href="/manifest.json" crossorigin="use-credentials" />');
if(!html.includes('mobile-pwa.js'))html=html.replace('</head>','<link rel="stylesheet" href="/assets/mobile.css"><script defer src="/assets/mobile-pwa.js"></script></head>');
const cssVersion=createHash('sha256').update(await readFile(new URL('mobile.css',import.meta.url))).digest('hex').slice(0,12);
html=html.replace(/href="\/assets\/mobile\.css(?:\?[^"]*)?"/,'href="/assets/mobile.css?v='+cssVersion+'"');
const scriptVersion=createHash('sha256').update(await readFile(new URL('mobile-pwa.js',import.meta.url))).digest('hex').slice(0,12);
html=html.replace(/src="\/assets\/mobile-pwa\.js(?:\?[^" ]*)?"/,'src="/assets/mobile-pwa.js?v='+scriptVersion+'"');
html=withPwaHead(html);
html=await withStartupAssets(html,fileURLToPath(root),'/');
await writeFile(new URL('index.html',root),html);
await copyFile(new URL('mobile.css',import.meta.url),new URL('assets/mobile.css',root));
await copyFile(new URL('mobile-pwa.js',import.meta.url),new URL('assets/mobile-pwa.js',root));
await copyFile(new URL('sw.js',import.meta.url),new URL('sw.js',root));
await sharp(new URL('assets/pwa-icon-512.png',root).pathname.replace(/^\/([A-Z]:)/,'$1')).resize(192,192).toFile(new URL('assets/pwa-icon-192.png',root).pathname.replace(/^\/([A-Z]:)/,'$1'));
const manifest=JSON.parse(await readFile(new URL('manifest.json',root),'utf8'));
Object.assign(manifest,{id:'/',name:'Codex Web',short_name:'Codex',scope:'/',theme_color:pwaBackgrounds.light,background_color:pwaBackgrounds.light});
manifest.icons=manifest.icons.filter(icon=>icon.src!=='/assets/pwa-icon-192.png');
manifest.icons.unshift({src:'/assets/pwa-icon-192.png',sizes:'192x192',type:'image/png',purpose:'any'});
await writeFile(new URL('manifest.json',root),JSON.stringify(manifest,null,2));
console.log('Mobile layout and network-only PWA installed');
